#!/usr/bin/env node
/**
 * Create dedicated outbid wallets under /home/twzrd/security/wallets/outbid.
 * Never prints private keys. Does not touch TWZRD Path A / feePayer / merchant keys.
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";

const DIR = process.env.OUTBID_WALLET_DIR || "/home/twzrd/security/wallets/outbid";
const ROOT = path.dirname(DIR);
const force = process.argv.includes("--force");

function ensureDir(p, mode = 0o700) {
  fs.mkdirSync(p, { recursive: true, mode });
  fs.chmodSync(p, mode);
}

function writeSecret(file, body) {
  if (fs.existsSync(file) && !force) {
    console.error(`exists, skip (use --force): ${file}`);
    return false;
  }
  fs.writeFileSync(file, body, { mode: 0o600 });
  fs.chmodSync(file, 0o600);
  return true;
}

function solanaKeygen(outFile) {
  const bin = spawnSync("solana-keygen", ["new", "--outfile", outFile, "--no-bip39-passphrase", "--force", "--silent"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
  if (bin.status !== 0) {
    throw new Error(`solana-keygen failed: ${bin.stderr || bin.stdout}`);
  }
  fs.chmodSync(outFile, 0o600);
  const pub = spawnSync("solana-keygen", ["pubkey", outFile], { encoding: "utf8" });
  if (pub.status !== 0) throw new Error(pub.stderr);
  return pub.stdout.trim();
}

ensureDir("/home/twzrd/security");
ensureDir(ROOT);
ensureDir(DIR);

const evmRoles = ["receiver", "payer"];
const evm = {};
for (const role of evmRoles) {
  const file = path.join(DIR, `${role}.evm.json`);
  if (fs.existsSync(file) && !force) {
    evm[role] = JSON.parse(fs.readFileSync(file, "utf8")).address;
    console.log(`keep ${role}.evm ${evm[role]}`);
    continue;
  }
  const privateKey = generatePrivateKey();
  const account = privateKeyToAccount(privateKey);
  writeSecret(
    file,
    JSON.stringify(
      {
        role: `outbid-${role}`,
        chain: "eip155:84532",
        address: account.address,
        privateKey,
      },
      null,
      2,
    ) + "\n",
  );
  evm[role] = account.address;
  console.log(`wrote ${role}.evm ${account.address}`);
}

const svm = {};
for (const role of ["receiver", "payer"]) {
  const file = path.join(DIR, `${role}.svm.json`);
  const pubFile = path.join(DIR, `${role}.svm.pubkey`);
  if (fs.existsSync(file) && !force) {
    svm[role] = fs.existsSync(pubFile)
      ? fs.readFileSync(pubFile, "utf8").trim()
      : spawnSync("solana-keygen", ["pubkey", file], { encoding: "utf8" }).stdout.trim();
    console.log(`keep ${role}.svm ${svm[role]}`);
    continue;
  }
  const pubkey = solanaKeygen(file);
  fs.writeFileSync(pubFile, pubkey + "\n", { mode: 0o644 });
  svm[role] = pubkey;
  console.log(`wrote ${role}.svm ${pubkey}`);
}

const manifest = `# Outbid wallets

Store: \`${DIR}\` (mode 700). Secret files are 600. Never commit them.

These are **dedicated** to outbid. They are not the TWZRD Path A payTo
(\`GFpLvoc…\`), not the settle feePayer (\`4LkEFj…\`), not the x402 merchant
keys in Doppler.

| Role | Chain | Public address | Secret file |
|---|---|---|---|
| receiver (402 payTo) | Base Sepolia \`eip155:84532\` | \`${evm.receiver}\` | \`receiver.evm.json\` |
| payer (bids) | Base Sepolia | \`${evm.payer}\` | \`payer.evm.json\` |
| receiver (402 payTo) | Solana devnet | \`${svm.receiver}\` | \`receiver.svm.json\` |
| payer (bids) | Solana devnet | \`${svm.payer}\` | \`payer.svm.json\` |

Hardhat/Anvil well-known keys (used only in \`test/x402.e2e.test.js\`) must never
be funded on any live network.

Funding: testnet only. Do not drain Path A / feePayer USDC into these.
`;

fs.writeFileSync(path.join(DIR, "MANIFEST.md"), manifest, { mode: 0o644 });
fs.writeFileSync(path.join(ROOT, "MANIFEST.md"), `# Wallet store\n\n- \`outbid/\` — pay-to-rank board (see outbid/MANIFEST.md)\n- Doppler \`X402_MERCHANT_KEYPAIR_FILE\` expected \`x402-merchant.json\` here; **file is not on this box**.\n`, { mode: 0o644 });

const envLive = `# generated by scripts/init-wallets.mjs — gitignored
# Receiver addresses (public). Payer secrets stay in the wallet dir.
EVM_ADDRESS=${evm.receiver}
SVM_ADDRESS=${svm.receiver}
EVM_PRIVATE_KEY_FILE=${path.join(DIR, "payer.evm.json")}
SVM_PRIVATE_KEY_FILE=${path.join(DIR, "payer.svm.json")}
OUTBID_WALLET_DIR=${DIR}
FACILITATOR_URL=https://x402.org/facilitator
EVM_NETWORK=eip155:84532
SVM_NETWORK=solana:EtWTRABZaYq6iMfeYKouRu166VU2xqa1
X402_DRY=0
PORT=4022
HOST=127.0.0.1
DATA_FILE=./data/board.json
`;
const envLivePath = path.join(path.dirname(new URL(import.meta.url).pathname), "..", ".env.live");
fs.writeFileSync(envLivePath, envLive, { mode: 0o600 });
console.log(`wrote ${envLivePath}`);
console.log(`manifest ${path.join(DIR, "MANIFEST.md")}`);
